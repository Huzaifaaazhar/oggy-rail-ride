const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1100, height: 700 } });
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await page.goto('http://localhost:5173/?seed=3&autopilot', { waitUntil: 'load' });
  await page.waitForTimeout(6000);
  await page.evaluate(() => { const p = JSON.parse(localStorage.getItem('bb-profile-v1') || '{}'); });
  await page.screenshot({ path: '/tmp/claude-0/m-home.png' });
  const go = async (label, name) => { await page.getByRole('button', { name: label, exact: true }).click(); await page.waitForTimeout(1500); await page.screenshot({ path: `/tmp/claude-0/m-${name}.png` }); await page.getByRole('button', { name: 'Back' }).click(); await page.waitForTimeout(300); };
  await go('Characters', 'cast');
  await page.getByRole('button', { name: 'Characters', exact: true }).click();
  await page.getByRole('button', { name: 'Next character' }).click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: '/tmp/claude-0/m-cast2.png' });
  await page.getByRole('button', { name: 'Back' }).click();
  await go('High scores', 'scores');
  await go('Achievements', 'awards');
  await go('Settings', 'settings');
  await page.getByRole('button', { name: /Daily challenge/ }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: '/tmp/claude-0/m-daily.png' });
  await page.getByRole('button', { name: 'Back' }).click();
  await page.getByRole('button', { name: 'Start the chase' }).click();
  await page.evaluate(() => window.__game.advance(10));
  await page.waitForTimeout(800);
  await page.screenshot({ path: '/tmp/claude-0/m-play.png' });
  await page.keyboard.press('Escape');
  await page.waitForTimeout(500);
  await page.screenshot({ path: '/tmp/claude-0/m-pause.png' });
  console.log(errs.slice(0, 8).join('\n'));
  await browser.close();
})();
